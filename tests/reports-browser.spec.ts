test("REL-04/06/UI-01: relatório filtra recebimentos e CSV exporta o mesmo conjunto sem alterar operação", async ({ page }) => {
  await seedDiagnosticsBrowser(page);
  await page.goto("/demo/relatorios/");
  await expect(page.getByRole("heading", { name: "Relatórios", exact: true })).toBeVisible();
  const before = await savedOperational(page);
  await page.getByRole("combobox", { name: "Tipo de relatório", exact: true }).selectOption("receipts");
  await page.getByLabel("Data inicial", { exact: true }).fill("2026-10-17");
  await page.getByLabel("Data final", { exact: true }).fill("2026-10-17");
  await page.getByRole("combobox", { name: "Consumidor", exact: true }).selectOption("c3");
  await page.getByRole("combobox", { name: "Meio", exact: true }).selectOption("transfer");
  await page.getByRole("combobox", { name: "Conta", exact: true }).selectOption("bank-qa");
  const region = page.getByRole("region", { name: "Linhas do relatório", exact: true });
  await expect(region.getByRole("row")).toHaveCount(2);
  await expect(region).toContainText("R$ 33,34");
  await expect(region).toContainText("Rafael Almeida");
  await expect(region).not.toContainText("Estúdio Forma");
  const pending = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar CSV", exact: true }).click();
  const csv = await downloadedText(await pending);
  const rows = parseReportsCsv(csv);
  expect(rows.filter((row) => row.includes("Rafael Almeida"))).toHaveLength(1);
  expect(csv).not.toContain("Estúdio Forma");
  expect(csv).toContain("2026-10-17");
  expect(csv).toContain("bank-qa");
  expect(await savedOperational(page)).toBe(before);
  await page.getByRole("combobox", { name: "Meio", exact: true }).selectOption("pix");
  await expect(page.getByText(/nenhum (recebimento|registro|resultado|dado)/i).first()).toBeVisible();
  const emptyDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar CSV", exact: true }).click();
  expect(await downloadedText(await emptyDownload)).not.toContain("Rafael Almeida");
  expect(await savedOperational(page)).toBe(before);
});

