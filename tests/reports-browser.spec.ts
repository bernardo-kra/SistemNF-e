test("UI-01: navegação, filtros por teclado e intervalo recuperável em 390 px sem overflow da página", async ({ page }) => {
  await seedDiagnosticsBrowser(page);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/demo/relatorios/");
  await expect(page.getByRole("heading", { name: "Relatórios", exact: true })).toBeVisible();
  const type = page.getByRole("combobox", { name: "Tipo de relatório", exact: true });
  await type.focus();
  await page.keyboard.press("s");
  await page.keyboard.press("Tab");
  await expect(page.getByLabel("Data inicial", { exact: true })).toBeFocused();
  await page.getByLabel("Data inicial", { exact: true }).fill("2026-10-18");
  await page.getByLabel("Data final", { exact: true }).fill("2026-10-17");
  await expect(page.getByRole("main").getByRole("alert")).toBeVisible();
  await expect(page.getByRole("button", { name: "Exportar CSV", exact: true })).toBeDisabled();
  await page.getByLabel("Data inicial", { exact: true }).fill("2026-10-16");
  await expect(page.getByRole("main").getByRole("alert")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Exportar CSV", exact: true })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Abrir navegação", exact: true }).click();
  await page.getByRole("link", { name: "Diagnóstico", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Diagnóstico", exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Nível", exact: true }).focus();
  await page.keyboard.press("e");
  await page.keyboard.press("Tab");
  await expect(page.getByRole("combobox", { name: "Módulo", exact: true })).toBeFocused();
  await page.getByLabel("De", { exact: true }).fill("2026-10-18");
  await page.getByLabel("Até", { exact: true }).fill("2026-10-17");
  await expect(page.getByRole("main").getByRole("alert")).toBeVisible();
  await page.getByLabel("De", { exact: true }).fill("2026-10-16");
  await expect(page.getByRole("main").getByRole("alert")).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test("REL-06: linha, total comercial e CSV preservam centavos seguros sem arredondar a apresentação", async ({ page }) => {
  const state = reportsFixture();
  state.finance = defaultFinance();
  const sale = state.sales.find((item) => item.id === "s400")!;
  sale.total = 9007199254740987;
  sale.items = [{ productId: "p3", quantity: 1, unitPrice: 9007199254740987 }];
  await seedDiagnosticsBrowser(page, state);
  await page.goto("/demo/relatorios/");
  await expect(page.getByRole("button", { name: "Exportar CSV", exact: true })).toBeEnabled();
  // Filtrar antes da consulta de Vendas evita somar outro registro ao limite.
  await page.getByRole("combobox", { name: "Consumidor", exact: true }).selectOption("c3");
  await page.getByRole("combobox", { name: "Tipo de relatório", exact: true }).selectOption("sales");
  const pending = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar CSV", exact: true }).click();
  expect(parseReportsCsv(await downloadedText(await pending)).flat()).toContain("90071992547409,87");
  const row = page.getByRole("region", { name: "Linhas do relatório", exact: true }).getByRole("row").filter({ hasText: "Venda #400" });
  await expect(row).toContainText("R$ 90.071.992.547.409,87");
  await expect(page.getByRole("region", { name: "Totais do relatório", exact: true })).toContainText("R$ 90.071.992.547.409,87");
});
