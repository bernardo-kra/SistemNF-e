import assert from "node:assert/strict";
import { before, after, test } from "node:test";
import { createHash, X509Certificate } from "node:crypto";
import { gzipSync } from "node:zlib";
import { SignedXml } from "xml-crypto";
import forge from "node-forge";
import { createA1Fixture } from "./nfse-a1-fixture.ts";
import { candidateXml, candidateKey, structuralSignature } from "./nfse-response-fixture.ts";
import { unsignedDpsXml } from "./nfse-dps-fixture.ts";
import { signDpsOffline, experimentalSignatureProfile } from "../src/nfse-dps-signature.ts";

const load = (): Promise<typeof import("../src/nfse-response-validation.ts")> => process.env.SISTEM_QA_COMPILED_RESPONSE === "true"
  ? import(new URL("../dist/nfse-response-validation.js", import.meta.url).href) : import("../src/nfse-response-validation.ts");
let service: Awaited<ReturnType<typeof load>>, fixture: Awaited<ReturnType<typeof createA1Fixture>>, dps: string, xml: string;
const ds="http://www.w3.org/2000/09/xmldsig#", c14n="http://www.w3.org/TR/2001/REC-xml-c14n-20010315", rsa="http://www.w3.org/2001/04/xmldsig-more#rsa-sha256", digest="http://www.w3.org/2001/04/xmlenc#sha256";
before(async () => {
  service=await load();
  assert.equal(typeof service.verifyNfseCandidateSignature,"function"); // RED before private fixture creation.
  fixture=await createA1Fixture(["valid","different","weak","ca"]);
  dps=signDpsOffline({xml:unsignedDpsXml,issuerCnpj:"11222333000181",at:fixture.now,profile:experimentalSignatureProfile,credentials:{pfx:fixture.materials.valid.pfx,passphrase:fixture.passphrase}}).xml;
  xml=signCandidate();
});
after(async () => { await fixture?.close(); });

// The response signature is generated by the independent test-only XMLDSig library.
function signCandidate(name="different", algorithm=rsa, hash=digest, publicCert=fixture.materials[name].certificatePem) {
  const signer=new SignedXml({privateKey:fixture.materials[name].keyPem,publicCert,signatureAlgorithm:algorithm,canonicalizationAlgorithm:c14n});
  signer.addReference({xpath:"/*[local-name()='NFSe']/*[local-name()='infNFSe']",transforms:[ds+"enveloped-signature",c14n],digestAlgorithm:hash});
  const unsigned=candidateXml(dps).replace(structuralSignature("NFS"+candidateKey),"");
  signer.computeSignature(unsigned,{location:{reference:"/*[local-name()='NFSe']/*[local-name()='infNFSe']",action:"after"}});
  return signer.getSignedXml();
}
const input=(value=xml,patch:Record<string,unknown>={})=>({expectedDpsXml:dps,nfseXmlGZipB64:gzipSync(value).toString("base64"),expectedAccessKey:candidateKey,expectedSignerCertificatePem:fixture.materials.different.certificatePem,at:fixture.now,...patch});
const safe=(code?:string)=>(error:any)=>{assert.equal(error.name,"NfseResponseError");if(code)assert.equal(error.code,code);assert.equal(error.cause,undefined);assert.doesNotMatch(String(error)+JSON.stringify(error),/BEGIN|PRIVATE KEY|<NFSe|<DPS|11222333000181/);assert.ok(!JSON.stringify(error).includes(fixture.passphrase));return true;};
function malformedExpiry(name: string) {
  const tree=forge.asn1.fromDer(new X509Certificate(fixture.materials[name].certificatePem).raw.toString("binary"));
  const tbs=(tree.value as forge.asn1.Asn1[])[0].value as forge.asn1.Asn1[];
  (tbs[4].value as forge.asn1.Asn1[])[1].value="991399999999Z";
  const raw=Buffer.from(forge.asn1.toDer(tree).getBytes(),"binary");
  const pem="-----BEGIN CERTIFICATE-----\n"+raw.toString("base64").match(/.{1,64}/g)!.join("\n")+"\n-----END CERTIFICATE-----\n";
  assert.equal(Number.isFinite(Date.parse(new X509Certificate(pem).validTo)),false);
  return {raw,pem};
}

test("SV01 assinatura independente válida confere matematicamente, sem autoridade fiscal",()=>{
  const checked=service.verifyNfseCandidateSignature(input());
  assert.equal(checked.state,"candidate_signature_verified");assert.equal(checked.signatureVerified,true);assert.equal(checked.certificateMatched,true);
  assert.equal(checked.signerFingerprint256,createHash("sha256").update(new X509Certificate(fixture.materials.different.certificatePem).raw).digest("hex"));
  for(const key of ["officialProfileConfirmed","trustChainVerified","revocationChecked","contractConfirmed","officialAuthorization","readyForSubmission"] as const)assert.equal(checked[key],false);
  for(const key of ["xml","certificatePem","expectedSignerCertificatePem","customerName","payload"])assert.equal(Object.hasOwn(checked,key),false);
  assert.equal(service.inspectNfseCandidate({expectedDpsXml:dps,nfseXmlGZipB64:gzipSync(xml).toString("base64")}).signatureVerified,false);
});

test("SV02 certificado esperado é obrigatório e separado do KeyInfo/A1 da loja",()=>{
  for(const expectedSignerCertificatePem of [undefined,"",fixture.materials.valid.certificatePem,fixture.materials.valid.keyPem,"x".repeat(65537)])
    assert.throws(()=>service.verifyNfseCandidateSignature(input(undefined,{expectedSignerCertificatePem})),safe());
});

test("SV03 adulteração do conteúdo da nota ou SignatureValue é detectada",()=>{
  for(const changed of [xml.replace("Emitente genérico QA","Outro emitente QA"),xml.replace("<vLiq>123.45","<vLiq>123.46"),xml.replace(/(<SignatureValue>)([^<]+)(<\/SignatureValue>)(?![\s\S]*<SignatureValue>)/,(_all,before,content,after)=>before+(content[0]==="A"?"B":"A")+content.slice(1)+after)])
    assert.throws(()=>service.verifyNfseCandidateSignature(input(changed)),safe("NFSE_SIGNATURE_INVALID"));
});

test("SV04 digest externo inclui assinatura interna da DPS e não a remove por transform",()=>{
  const changedDps=dps.replace(/<SignatureValue>([^<]+)/,(_all,value)=>"<SignatureValue>"+(value[0]==="A"?"B":"A")+value.slice(1));
  const changed=xml.replace(dps.replace(/<\?xml[^?]*\?>\s*/,""),changedDps.replace(/<\?xml[^?]*\?>\s*/,""));
  assert.notEqual(changed,xml);
  assert.throws(()=>service.verifyNfseCandidateSignature(input(changed,{expectedDpsXml:changedDps})),safe("NFSE_SIGNATURE_INVALID"));
});

test("SV05 algoritmo e transformações fora do perfil fechado não são adaptados",()=>{
  const legacy=signCandidate("different",ds+"rsa-sha1",ds+"sha1");
  const transform=xml.replace(/(<Transform Algorithm=")http:\/\/www.w3.org\/TR\/2001\/REC-xml-c14n-20010315("\/?>)(?![\s\S]*<Transform Algorithm="http:\/\/www.w3.org\/TR\/2001\/REC-xml-c14n-20010315)/,"$1http://www.w3.org/TR/1999/REC-xslt-19991116$2");
  assert.notEqual(transform,xml);
  for(const changed of [legacy,transform])assert.throws(()=>service.verifyNfseCandidateSignature(input(changed)),safe("NFSE_SIGNATURE_INVALID"));
});

test("SV06 instantes explícitos e validade do certificado não são deduzidos do XML",()=>{
  const cert=new X509Certificate(fixture.materials.different.certificatePem);
  for(const at of [undefined,new Date(NaN),fixture.now.toISOString(),new Date(Date.parse(cert.validFrom)-1000),new Date(Date.parse(cert.validTo)+1000)])
    assert.throws(()=>service.verifyNfseCandidateSignature(input(undefined,{at})),safe());
});

test("SV07 certificado CA ou RSA fraco não passa mesmo com assinatura matemática",()=>{
  for(const name of ["weak","ca"])assert.throws(()=>service.verifyNfseCandidateSignature(input(signCandidate(name),{expectedSignerCertificatePem:fixture.materials[name].certificatePem})),safe());
});

test("SV08 fonte/chave divergentes e campos inventados continuam bloqueados",()=>{
  for(const patch of [{expectedDpsXml:dps.replace("Cliente QA","Outro QA")},{expectedAccessKey:"1".repeat(50)},{officialAuthorization:true},{profile:"official"}])
    assert.throws(()=>service.verifyNfseCandidateSignature(input(undefined,patch)),safe());
});

test("SV09 data ASN.1 inválida do certificado não pode passar por comparação com NaN",()=>{
  const malformed=malformedExpiry("different");
  assert.throws(()=>service.verifyNfseCandidateSignature(input(signCandidate("different",rsa,digest,malformed.pem),{expectedSignerCertificatePem:malformed.pem})),safe("NFSE_SIGNATURE_INVALID"));
});

test("SV10 verificação DPS legada também recusa data ASN.1 inválida sem promover validade",async()=>{
  const malformed=malformedExpiry("valid"),changed=dps.replace(/<X509Certificate>[^<]+<\/X509Certificate>/,`<X509Certificate>${malformed.raw.toString("base64")}</X509Certificate>`);
  const legacy=process.env.SISTEM_QA_COMPILED_RESPONSE==="true"?await import(new URL("../dist/nfse-dps-signature.js",import.meta.url).href):await import("../src/nfse-dps-signature.ts");
  assert.throws(()=>legacy.verifyDpsOffline({xml:changed,certificatePem:malformed.pem,issuerCnpj:"11222333000181",at:fixture.now,profile:experimentalSignatureProfile}),(error:any)=>{
    assert.equal(error.name,"NfseDpsSignatureError");assert.equal(error.code,"CERTIFICATE_NOT_VALID_AT_TIME");return true;
  });
});
